export interface Rapor {
  ringkasan: Ringkasan;
  soal: readonly Soal[];
  penilaian: readonly Penilaian[];
  detik: number;
  benih: string;
}

/**
 * Seluruh isi rapor sebagai baris CSV.
 *
 * `pilih` diserahkan pemanggilnya alih-alih diimpor langsung dari modul rune,
 * supaya berkas ini tetap bisa diimpor CPython-nya Vitest — modul rune hanya
 * bisa diurai perkakas Svelte, dan kode yang tidak bisa diimpor tidak bisa
 * diuji.
 */
export function barisRapor(rapor: Rapor, pilih: (p: Bilingual) => string): Sel[][] {
  const baris: Sel[][] = [];
  const L = LABEL;

  baris.push([pilih(L.judul)]);
  baris.push([pilih(L.dihasilkan), "xyb3rpunq.github.io/ind323-ai-lab (.Deckyx)"]);
  // Bahasanya dicatat supaya rapor yang beredar lepas dari halamannya tetap
  // bisa ditelusuri asalnya. Kodenya diambil dari `pilih` itu sendiri: ia
  // memang fungsi yang memilih salah satu dari sepasang, jadi memberinya
  // pasangan berisi kedua kode bahasa mengembalikan yang sedang aktif.
  baris.push([pilih(L.bahasa), pilih(bi("id", "en"))]);
  baris.push([]);

  baris.push([pilih(L.ringkasan)]);
  baris.push([pilih(L.nilai), Math.round(rapor.ringkasan.nilai)]);
  baris.push([pilih(L.benar), rapor.ringkasan.benar]);
  baris.push([pilih(L.total), rapor.ringkasan.total]);
  baris.push([pilih(L.waktu), rapor.detik]);
  baris.push([pilih(L.benih), rapor.benih]);
  baris.push([]);

  baris.push([pilih(L.perTopik)]);
  baris.push([pilih(L.topik), pilih(L.benar), pilih(L.total), pilih(L.bagian)]);
  for (const t of rapor.ringkasan.perTopik) {
    baris.push([
      pilih(namaTopik(t.topik)),
      t.benar,
      t.total,
      t.total > 0 ? t.benar / t.total : 0,
    ]);
  }
  baris.push([]);

  baris.push([pilih(L.rincian)]);
  baris.push([
    pilih(L.no),
    pilih(L.kode),
    pilih(L.sesi),
    pilih(L.topik),
    pilih(L.pertanyaan),
    pilih(L.hasilnya),
    pilih(L.pembahasan),
  ]);
  rapor.soal.forEach((s, i) => {
    // Penilaian dicocokkan lewat kodenya, bukan lewat urutannya. Sebuah sesi
    // yang ditinggalkan di tengah menghasilkan penilaian yang lebih pendek
    // daripada soalnya, dan mencocokkan berdasar indeks akan menggeser seluruh
    // baris sesudahnya tanpa satu pun galat.
    const p = rapor.penilaian.find((x) => x.kode === s.kode);
    baris.push([
      i + 1,
      s.kode,
      s.sesi,
      pilih(namaTopik(s.topik)),
      pilih(s.pertanyaan),
      p === undefined ? "" : pilih(p.benar ? L.ya : L.tidak),
      pilih(s.pembahasan),
    ]);
  });
  baris.push([]);

  baris.push([pilih(L.catatan)]);
  baris.push([pilih(L.catatanBenih)]);
  baris.push([pilih(L.catatanDesimal)]);
  return baris;
}

/** Nama berkas yang menyebutkan benih dan nilainya, bukan sekadar tanggal. */
export function namaBerkas(rapor: Rapor, akhiran = "csv"): string {
  const kini = new Date();
  const dua = (n: number) => String(n).padStart(2, "0");
  const cap = `${kini.getFullYear()}${dua(kini.getMonth() + 1)}${dua(kini.getDate())}`;
  // Benih berasal dari isian pengguna dan bisa memuat apa saja. Dibersihkan
  // sebelum masuk ke nama berkas: titik dua dan garis miring membuat unduhan
  // gagal senyap di Windows.
  const benih = rapor.benih.replace(/[^0-9A-Za-z-]/g, "").slice(0, 20) || "0";
  const nilai = Math.round(rapor.ringkasan.nilai);
  return `ind323-rapor-${cap}-benih${benih}-nilai${nilai}.${akhiran}`;
}

/** Menyerahkan sebuah berkas kepada pengguna. */
export function unduh(nama: string, teks: string, jenis: string): void {
  const gumpal = new Blob([teks], { type: jenis });
  const alamat = URL.createObjectURL(gumpal);
  const tautan = document.createElement("a");
  tautan.href = alamat;
  tautan.download = nama;
  document.body.append(tautan);
  tautan.click();
  tautan.remove();
  // Yang tidak dilepas menahan seluruh isi berkasnya di memori sampai tabnya
  // ditutup.
  URL.revokeObjectURL(alamat);
}

/** Menyusun rapor menjadi CSV lalu mengunduhnya. */
export function unduhRapor(rapor: Rapor, pilih: (p: Bilingual) => string): string {
  const nama = namaBerkas(rapor);
  unduh(nama, csv(barisRapor(rapor, pilih)), "text/csv;charset=utf-8");
  return nama;
}
