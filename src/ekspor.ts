/**
 * Menyusun hasil sesi latihan menjadi berkas yang bisa disimpan.
 *
 * # Kenapa CSV dan bukan XLSX
 *
 * XLSX adalah arsip ZIP berisi beberapa berkas XML, dan menyusunnya di
 * peramban menuntut pustaka berukuran ratusan kilobyte — beberapa kali lipat
 * seluruh situs ini, yang hanya 52 KB. CSV dibuka Excel, Google Sheets, dan
 * pandas tanpa satu bita pun tambahan.
 *
 * Tiga hal yang wajib benar agar berkasnya sungguh terbuka rapi di Excel:
 * BOM UTF-8 di depan (tanpa itu Excel di Windows membacanya sebagai ANSI),
 * baris `sep=,` paling atas (Excel berwilayah Indonesia memakai titik koma),
 * dan akhir baris CRLF seperti dituntut RFC 4180.
 *
 * # Kenapa isinya mengikuti bahasa yang sedang aktif
 *
 * Karena berkas ini dibaca oleh orang yang sama yang baru saja mengerjakan
 * sesinya. Rapor berbahasa Indonesia untuk sesi yang dikerjakan dalam bahasa
 * Inggris memaksa pembacanya menerjemahkan sendiri istilah yang barusan ia
 * baca dalam bahasa lain.
 *
 * .Deckyx
 */

import { namaTopik } from "./bank";
import type { Penilaian, Ringkasan, Soal } from "./bank";
import { bi, type Bilingual } from "./i18n";

const CR = String.fromCharCode(13);
const LF = String.fromCharCode(10);
const AKHIR_BARIS = CR + LF;
const BOM = "﻿";

export type Sel = string | number | null | undefined;

/** Satu sel CSV, dikutip bila perlu. */
export function sel(nilai: Sel): string {
  if (nilai === null || nilai === undefined) return "";
  const teks = typeof nilai === "number" ? String(nilai) : nilai;
  if (/[",\r\n]/.test(teks)) return `"${teks.replace(/"/g, '""')}"`;
  return teks;
}

/** Menyusun baris menjadi teks CSV yang siap diunduh. */
export function csv(baris: Sel[][]): string {
  const isi = [`${BOM}sep=,`];
  for (const b of baris) isi.push(b.map(sel).join(","));
  return isi.join(AKHIR_BARIS) + AKHIR_BARIS;
}

